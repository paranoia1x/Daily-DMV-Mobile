"""Render the handbook PDF into page images plus word boxes and highlight boxes for the in-app reader.
Maintenance only (needs the PyMuPDF package). Run after tools/highlight-handbook.py:
    python tools/build-handbook-pages.py [PYLIB_DIR]
Reads  app/handbook/california-driver-handbook-highlighted.pdf and app/data/handbook-index.js
Writes app/handbook/pages/p001.jpg ... and app/data/handbook-pages.js"""
import json, os, re, sys
if len(sys.argv) > 1:
    sys.path.insert(0, sys.argv[1])
import pymupdf

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
APP = os.path.join(ROOT, 'app')
pdf = pymupdf.open(os.path.join(APP, 'handbook', 'california-driver-handbook-highlighted.pdf'))
idx_js = open(os.path.join(APP, 'data', 'handbook-index.js'), encoding='utf-8').read()
index = json.loads(re.search(r'window\.HANDBOOK = (\{.*\});', idx_js, re.S).group(1))['highlights']
out_dir = os.path.join(APP, 'handbook', 'pages')
os.makedirs(out_dir, exist_ok=True)
WIDTH = 1100
pages = []
r4 = lambda v: round(v, 4)
for i in range(pdf.page_count):
    page = pdf[i]
    W, H = page.rect.width, page.rect.height
    pix = page.get_pixmap(matrix=pymupdf.Matrix(WIDTH / W, WIDTH / W), annots=False)
    name = f'p{i + 1:03d}.jpg'
    pix.save(os.path.join(out_dir, name), jpg_quality=78)
    words = [[r4(w[0] / W), r4(w[1] / H), r4(w[2] / W), r4(w[3] / H)] for w in page.get_text('words')]
    # highlight boxes, in the same order the annotations were added (matches index order for this page)
    page_idx = [n for n, h in enumerate(index) if h['page'] == i + 1]
    hl, k = [], 0
    for a in page.annots(types=[pymupdf.PDF_ANNOT_HIGHLIGHT]):
        v = a.vertices
        n = page_idx[k] if k < len(page_idx) else -1
        k += 1
        for q in range(0, len(v), 4):
            xs = [p[0] for p in v[q:q + 4]]; ys = [p[1] for p in v[q:q + 4]]
            hl.append([r4(min(xs) / W), r4(min(ys) / H), r4(max(xs) / W), r4(max(ys) / H), n])
    pages.append({'img': 'handbook/pages/' + name, 'label': page.get_label() or str(i + 1), 'ratio': r4(H / W), 'w': words, 'hl': hl})
with open(os.path.join(APP, 'data', 'handbook-pages.js'), 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build-handbook-pages.py: page images, word boxes and highlight boxes (0-1 page units). */\n')
    f.write('window.HANDBOOK_PAGES = ' + json.dumps(pages, separators=(',', ':')) + ';\n')
total = sum(os.path.getsize(os.path.join(out_dir, p)) for p in os.listdir(out_dir))
print(f'{len(pages)} pages, images {total / 1e6:.1f} MB, highlight boxes {sum(len(p["hl"]) for p in pages)}')
