// Writes sw.js (offline support) with a precache list of the app files and a version hash.
// Run after changing any app file:  node tools/build-sw.js
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.join(__dirname, '..');
const list = ['index.html', 'manifest.webmanifest'];
for (const dir of ['css', 'js', 'data', 'img', 'handbook/fig']) {
  (function walk(d) {
    for (const f of fs.readdirSync(path.join(ROOT, d))) {
      const rel = d + '/' + f;
      if (fs.statSync(path.join(ROOT, rel)).isDirectory()) walk(rel); else list.push(rel);
    }
  })(dir);
}
const hash = crypto.createHash('sha256');
for (const f of list) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = hash.digest('hex').slice(0, 12);
const sw = `/* Generated by tools/build-sw.js. Offline support for CA Driver Test Practice. */
const VERSION = '${version}';
const CORE = 'dmv-core-' + VERSION;
const PAGES = 'dmv-handbook-pages-v1'; // handbook page images; kept across updates
const PRECACHE = ${JSON.stringify(list, null, 1)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CORE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('dmv-core-') && k !== CORE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // official links etc. go straight to the network
  if (url.pathname.includes('/handbook/pages/')) {
    e.respondWith(caches.open(PAGES).then(async c => {
      const hit = await c.match(req, { ignoreSearch: true });
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) c.put(req, res.clone());
      return res;
    }));
    return;
  }
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('index.html')));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
`;
fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: ${list.length} files precached, version ${version}`);
